"""X-ray reference data for EDS: elements, characteristic lines, edges and attenuation.

Data: ``data/xray_data.npz``, generated by ``tools/gen_xray_data.py`` from xraydb
(Elam, Ravel & Sieber 2002 tables).  Energies are in **keV** throughout.

    from easyebl import xray
    xray.z_of("Fe")                       # 26
    xray.lines("Fe", "K")                 # [XrayLine(Fe Ka1 6.404 keV), ...]
    xray.main_line("Au", "M")             # Au Ma 2.123 keV
    xray.lines_near(6.40, tol=0.05)       # candidates for a peak at 6.40 keV
    xray.mac(6.404, 26)                   # µ/ρ of Fe at 6.404 keV (cm²/g)
"""
from __future__ import annotations

from dataclasses import dataclass
import functools
import os

import numpy as np

__all__ = [
    "XrayLine",
    "ELEMENTS",
    "z_of",
    "symbol",
    "atomic_mass",
    "lines",
    "main_line",
    "families",
    "lines_near",
    "family_label",
    "edge_energy",
    "mac",
    "mac_line",
    "mu_rho_mix",
    "normalize_composition",
    "data_source",
]

_PATH = os.path.join(os.path.dirname(__file__), "data", "xray_data.npz")
FAMILIES = ("K", "L", "M")


@functools.lru_cache(maxsize=1)
def _data() -> dict:
    with np.load(_PATH, allow_pickle=False) as f:
        d = {k: f[k] for k in f.files}
    d["shell_index"] = {str(s): i for i, s in enumerate(d["shells"])}
    return d


def data_source() -> str:
    return str(_data()["source"])


@functools.lru_cache(maxsize=1)
def _symbols() -> tuple:
    return tuple(str(s) for s in _data()["symbols"])


#: Element symbols indexed by Z (``ELEMENTS[26] == "Fe"``; index 0 is "").
ELEMENTS = _symbols()


def z_of(element) -> int:
    """Atomic number of a symbol ("Fe", case-insensitive) or an int Z."""
    if isinstance(element, (int, np.integer)):
        z = int(element)
        if not 1 <= z < len(ELEMENTS):
            raise ValueError(f"Z={z} outside 1…{len(ELEMENTS) - 1}")
        return z
    s = str(element).strip()
    s = s[:1].upper() + s[1:].lower()
    try:
        return ELEMENTS.index(s)
    except ValueError:
        raise ValueError(f"unknown element '{element}'") from None


def symbol(z) -> str:
    return ELEMENTS[z_of(z)]


def atomic_mass(z) -> float:
    return float(_data()["mass"][z_of(z)])


def edge_energy(element, shell: str) -> float:
    """Absorption edge energy (keV) of *shell* ("K", "L3", "M5" …); 0 if absent."""
    d = _data()
    return float(d["edge_e"][z_of(element), d["shell_index"][shell]])


@dataclass(frozen=True)
class XrayLine:
    """One characteristic line.

    ``weight`` is the relative intensity within its family (strongest line = 1),
    from subshell occupancy × fluorescence yield × branching ratio.
    ``strength`` is occupancy × fluorescence yield × branching (absolute scale
    used by the generation model).
    """

    z: int
    element: str
    name: str
    family: str
    shell: str
    energy: float
    weight: float
    strength: float
    edge: float
    fluor_yield: float
    index: int

    @property
    def label(self) -> str:
        return f"{self.element} {self.name}"

    def __repr__(self) -> str:
        return f"XrayLine({self.element} {self.name} {self.energy:.3f} keV, w={self.weight:.3f})"


@functools.lru_cache(maxsize=1)
def _all_lines() -> tuple:
    d = _data()
    strength = d["line_occ"] * d["line_fy"] * d["line_branch"]
    out = []
    # family maxima for the relative weights
    key = [(int(z), str(f)) for z, f in zip(d["line_z"], d["line_family"])]
    fam_max: dict = {}
    for k, s in zip(key, strength):
        fam_max[k] = max(fam_max.get(k, 0.0), float(s))
    for i, (z, f) in enumerate(key):
        out.append(
            XrayLine(
                z=z,
                element=ELEMENTS[z],
                name=str(d["line_name"][i]),
                family=f,
                shell=str(d["line_shell"][i]),
                energy=float(d["line_e"][i]),
                weight=float(strength[i] / fam_max[(z, f)]) if fam_max[(z, f)] > 0 else 0.0,
                strength=float(strength[i]),
                edge=float(d["line_edge"][i]),
                fluor_yield=float(d["line_fy"][i]),
                index=i,
            )
        )
    return tuple(out)


@functools.lru_cache(maxsize=None)
def _lines_of(z: int) -> tuple:
    return tuple(ln for ln in _all_lines() if ln.z == z)


def lines(element, family: str | None = None, beam_kv: float | None = None, min_weight: float = 0.0,
          e_min: float = 0.1) -> list[XrayLine]:
    """Lines of *element* (optionally one *family*), excited by *beam_kv* (edge < beam energy)."""
    z = z_of(element)
    out = []
    for ln in _lines_of(z):
        if family is not None and ln.family != family:
            continue
        if beam_kv is not None and ln.edge >= beam_kv:
            continue
        if ln.weight < min_weight or ln.energy < e_min:
            continue
        out.append(ln)
    return sorted(out, key=lambda l: (-l.weight, l.energy))


def main_line(element, family: str) -> XrayLine | None:
    """Strongest line of a family (e.g. Fe Ka1, Au Ma) or None."""
    ls = lines(element, family)
    return ls[0] if ls else None


def families(element, beam_kv: float | None = None, e_min: float = 0.1) -> list[str]:
    """Families with at least one excited line above *e_min* keV, e.g. ["K", "L"]."""
    z = z_of(element)
    fams = []
    for f in FAMILIES:
        if lines(z, f, beam_kv, e_min=e_min):
            fams.append(f)
    return fams


def family_label(element, family: str) -> str:
    """'Fe Kα'-style label of a family."""
    return f"{symbol(element)} {family}{'α' if family in ('K', 'L', 'M') else ''}"


def lines_near(energy: float, tol: float = 0.05, beam_kv: float | None = None, min_weight: float = 0.1,
               elements=None) -> list[XrayLine]:
    """Lines within ±*tol* keV of *energy* (closest and strongest first)."""
    zs = None if elements is None else {z_of(e) for e in elements}
    out = []
    for ln in _all_lines():
        if zs is not None and ln.z not in zs:
            continue
        if abs(ln.energy - energy) > tol or ln.weight < min_weight:
            continue
        if beam_kv is not None and ln.edge >= beam_kv:
            continue
        out.append(ln)
    return sorted(out, key=lambda l: (abs(l.energy - energy) / tol - l.weight, l.z))


# ------------------------------------------------------------ attenuation
def mac_line(line: XrayLine, absorber) -> float:
    """Mass attenuation coefficient µ/ρ (cm²/g) of *absorber* for *line*'s energy (exact table)."""
    return float(_data()["mac"][line.index, z_of(absorber)])


def mac(energy, absorber) -> np.ndarray | float:
    """µ/ρ (cm²/g) of *absorber* at *energy* keV (log-log interpolation on a 1 % grid)."""
    d = _data()
    z = z_of(absorber)
    e = np.asarray(energy, dtype=float)
    lg = np.log(d["grid_e"])
    val = np.exp(np.interp(np.log(np.clip(e, d["grid_e"][0], d["grid_e"][-1])), lg, np.log(d["mu_grid"][z])))
    return float(val) if np.ndim(val) == 0 else val


def normalize_composition(comp: dict) -> dict:
    """{element/Z: mass fraction} → {Z: fraction} summing to 1."""
    out: dict = {}
    for k, v in comp.items():
        if v < 0:
            raise ValueError("negative mass fraction")
        z = z_of(k)
        out[z] = out.get(z, 0.0) + float(v)
    tot = sum(out.values())
    if tot <= 0:
        raise ValueError("empty composition")
    return {z: v / tot for z, v in out.items()}


def mu_rho_mix(energy, comp: dict) -> np.ndarray | float:
    """µ/ρ of a mixture (mass fractions) at *energy* keV."""
    c = normalize_composition(comp)
    return sum(w * mac(energy, z) for z, w in c.items())
