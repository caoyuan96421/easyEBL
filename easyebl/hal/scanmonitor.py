"""Scan monitor: what an oscilloscope in XY mode with persistence would show (no Qt).

The streaming thread hands every written output chunk (X, Y volts and the
logical blank state, exactly as it went to the DAQ) to a :class:`ScanTap`.
A separate :class:`ScanMonitorWorker` thread drains the tap about ten times a
second, bins the *unblanked* samples into a :class:`PersistenceAccumulator`
(a 2-D histogram over the full ±10 V field) and renders an 8-bit intensity
image for the display.

Hand-off guarantees (the stream must never slow down):

* :meth:`ScanTap.push` never blocks and never allocates: it is a
  single-producer / single-consumer ring buffer of preallocated arrays, the
  producer only moves ``head`` and the consumer only moves ``tail``, so no
  lock is needed.
* When the ring is short of room the chunk is decimated (every *k*-th sample)
  to fit; when it is full the chunk is dropped.  Both are counted in
  :attr:`ScanTap.dropped`.
* A disabled tap (no display) returns at once.

The tap also knows where the beam is *now* (:meth:`ScanTap.position`):
the backend reports how many samples of the stream the device has generated
(:meth:`ScanTap.set_generated`) and every software-timed write
(:meth:`ScanTap.set_static`), and the tap keeps a few position marks per
pushed chunk.  So the spot follows the beam, not the host's write position,
which runs ahead by the output buffer.
"""
from __future__ import annotations

from dataclasses import dataclass
import math
import threading
import time
from typing import Callable

import numpy as np

__all__ = ["ScanTap", "PersistenceAccumulator", "ScanMonitorWorker", "MonitorStats", "phosphor_lut",
           "RESOLUTIONS", "FULL_SCALE_V"]

#: offered display resolutions (pixels per axis)
RESOLUTIONS = (64, 128, 256, 512, 1024)
#: the monitor always shows the full deflection range on both axes
FULL_SCALE_V = 10.0


# ==================================================================== hand-off
class ScanTap:
    """Bounded, lock-free, non-blocking hand-off of output samples between two threads.

    One producer (the DAQ streaming thread) calls :meth:`push`; one consumer
    (the monitor worker) calls :meth:`pop`.  Samples are stored as float32
    volts plus a bool blank flag.
    """

    #: position marks kept per pushed chunk (evenly spaced, first and last sample included)
    MARKS_PER_CHUNK = 16
    #: position-mark ring size
    N_MARKS = 1 << 13

    def __init__(self, capacity: int = 1 << 20):
        self.capacity = int(capacity)
        if self.capacity < 1:
            raise ValueError("capacity must be ≥ 1")
        self._x = np.empty(self.capacity, dtype=np.float32)
        self._y = np.empty(self.capacity, dtype=np.float32)
        self._b = np.empty(self.capacity, dtype=bool)
        self._head = 0  # samples ever stored (moved by the producer only)
        self._tail = 0  # samples ever consumed (moved by the consumer only)
        self.enabled = False
        self.pushed = 0  # samples offered while enabled
        self.dropped = 0  # of those: not stored (decimated away or dropped)
        # --- current beam position
        m = self.N_MARKS
        self._mi = np.zeros(m, dtype=np.int64)  # stream sample index of each mark
        self._mx = np.zeros(m, dtype=np.float32)
        self._my = np.zeros(m, dtype=np.float32)
        self._mb = np.ones(m, dtype=bool)
        self._mhead = 0  # marks ever stored (producer)
        self._mbase = 0  # first mark of the current stream
        self._sidx = 0  # samples pushed in the current stream (counted even when disabled)
        self._generated = 0  # samples of the current stream generated by the device
        self._streaming = False
        self._static: tuple[float, float, bool] | None = None  # last software-timed output

    # ------------------------------------------------------------ beam position (producer side)
    def begin_stream(self) -> None:
        """A hardware-timed stream starts: until its first sample plays the beam stays where it was."""
        self._sidx = 0
        self._generated = 0
        self._mbase = self._mhead
        self._streaming = True

    def set_generated(self, n: int) -> None:
        """The device has generated *n* samples of the current stream."""
        self._generated = int(n)

    def end_stream(self) -> None:
        self._streaming = False

    def set_static(self, x: float, y: float, blank: bool) -> None:
        """A software-timed write (no stream): the beam sits at (x, y)."""
        self._static = (float(x), float(y), bool(blank))
        self._streaming = False

    def _mark(self, x, y, blank, n: int) -> None:
        step = max(1, -(-n // self.MARKS_PER_CHUNK))
        j0 = (n - 1) % step  # so that the last sample is a mark
        h, m, base = self._mhead, self.N_MARKS, self._sidx
        for j in ((0,) if j0 else ()) + tuple(range(j0, n, step)):  # first and last sample included
            k = h % m
            self._mi[k] = base + j
            self._mx[k] = x[j]
            self._my[k] = y[j]
            self._mb[k] = blank[j]
            h += 1
        self._mhead = h

    # ------------------------------------------------------------ beam position (consumer side)
    def position(self) -> tuple[float, float, bool] | None:
        """Where the beam is now: (x volts, y volts, blanked) of the outputs, or None if unknown."""
        st = self._static
        if not self._streaming:
            return st
        g = self._generated
        h = self._mhead
        lo = max(self._mbase, h - self.N_MARKS)
        if g <= 0 or h <= lo:
            return st
        k = np.arange(lo, h) % self.N_MARKS
        mi = self._mi[k]
        ok = np.flatnonzero(mi <= g - 1)  # the newest sample already played
        # (none: the stream has begun, but before its first mark – the nearest one is closest)
        j = k[ok[np.argmax(mi[ok])]] if ok.size else k[np.argmin(mi)]
        return float(self._mx[j]), float(self._my[j]), bool(self._mb[j])

    @property
    def pending(self) -> int:
        return self._head - self._tail

    def push(self, x, y, blank) -> int:
        """Store one chunk; returns the number of samples kept.  Never blocks."""
        n = len(x)
        if not self.enabled:
            self._sidx += n
            return 0
        if n == 0:
            return 0
        self._mark(x, y, blank, n)
        self._sidx += n
        self.pushed += n
        head = self._head
        free = self.capacity - (head - self._tail)
        if free <= 0:
            self.dropped += n
            return 0
        if n > free:  # decimate to fit (keeps the shape of the pattern)
            step = -(-n // free)
            x, y, blank = x[::step], y[::step], blank[::step]
            self.dropped += n - len(x)
            n = len(x)
        i = head % self.capacity
        k = min(n, self.capacity - i)
        self._x[i:i + k] = x[:k]
        self._y[i:i + k] = y[:k]
        self._b[i:i + k] = blank[:k]
        if k < n:  # wrap around
            self._x[:n - k] = x[k:]
            self._y[:n - k] = y[k:]
            self._b[:n - k] = blank[k:]
        self._head = head + n  # publish only after the data is in place
        return n

    def pop(self) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        """Everything stored since the last pop (copies), oldest first."""
        tail, head = self._tail, self._head
        n = head - tail
        if n <= 0:
            e = np.empty(0, dtype=np.float32)
            return e, e.copy(), np.empty(0, dtype=bool)
        i = tail % self.capacity
        idx = (np.arange(n) + i) % self.capacity if i + n > self.capacity else slice(i, i + n)
        out = self._x[idx].copy(), self._y[idx].copy(), self._b[idx].copy()
        self._tail = head
        return out

    def clear(self) -> None:
        """Discard what is pending (consumer side)."""
        self._tail = self._head


# ==================================================================== accumulation
class PersistenceAccumulator:
    """2-D histogram of the unblanked beam positions with a finite retention time.

    Samples are binned into time buckets of ``retention_s / n_buckets``; a
    bucket is discarded once all of it is older than the retention time.
    With ``fade`` the buckets are weighted linearly from 1 (new) to 0 (at the
    retention time), like a phosphor trace; without it every retained sample
    counts fully.  ``retention_s <= 0`` keeps everything until :meth:`clear`.

    The image is in the field (image) coordinates of the other windows:
    ``invert_x`` / ``invert_y`` / ``swap_xy`` are those of the scan output
    (:class:`~easyebl.core.calibration.FieldCalibration`) and are undone, so a
    raster shows up the way the SEM image does.  Image row 0 is +full scale in
    field Y (top of the screen), column 0 is −full scale in field X.
    """

    def __init__(self, resolution: int = 256, retention_s: float = 2.0, fade: bool = True,
                 full_scale_v: float = FULL_SCALE_V, n_buckets: int = 16,
                 clock: Callable[[], float] = time.monotonic, invert_x: bool = False,
                 invert_y: bool = False, swap_xy: bool = False):
        self.resolution = int(resolution)
        if self.resolution < 2:
            raise ValueError("resolution must be ≥ 2")
        self.retention_s = float(retention_s)
        self.fade = bool(fade)
        self.full_scale_v = float(full_scale_v)
        self.n_buckets = max(1, int(n_buckets))
        self.clock = clock
        self.invert_x, self.invert_y, self.swap_xy = bool(invert_x), bool(invert_y), bool(swap_xy)
        self.total = 0  # unblanked samples binned since the last clear
        self._buckets: list[list] = []  # [t_start, hist (res*res float32)], oldest first

    @property
    def infinite(self) -> bool:
        return self.retention_s <= 0

    @property
    def bucket_s(self) -> float:
        return math.inf if self.infinite else self.retention_s / self.n_buckets

    def clear(self) -> None:
        self._buckets.clear()
        self.total = 0

    def _expire(self, now: float) -> None:
        if self.infinite:
            return
        b = self._buckets
        while b and b[0][0] + self.bucket_s <= now - self.retention_s:
            b.pop(0)

    def _current(self, now: float) -> np.ndarray:
        b = self._buckets
        if not b or now - b[-1][0] >= self.bucket_s:
            b.append([now, np.zeros(self.resolution * self.resolution, dtype=np.float32)])
        return b[-1][1]

    @property
    def orientation(self) -> tuple[bool, bool, bool]:
        return self.invert_x, self.invert_y, self.swap_xy

    def to_field(self, x, y) -> tuple[np.ndarray, np.ndarray]:
        """Output volts (X, Y deflection) → field volts (image X, Y): undo the inversions, then the swap."""
        x = np.asarray(x, dtype=np.float32)
        y = np.asarray(y, dtype=np.float32)
        if self.invert_x:
            x = -x
        if self.invert_y:
            y = -y
        return (y, x) if self.swap_xy else (x, y)

    def bin_index(self, x, y) -> np.ndarray:
        """Flat pixel index of each output (x, y) in volts; outside the field is clipped to the edge."""
        r = self.resolution
        s = r / (2.0 * self.full_scale_v)
        fx, fy = self.to_field(x, y)
        ix = np.clip(((fx + self.full_scale_v) * s).astype(np.int64), 0, r - 1)
        iy = np.clip(((fy + self.full_scale_v) * s).astype(np.int64), 0, r - 1)
        return (r - 1 - iy) * r + ix

    def add(self, x, y, blank, now: float | None = None) -> int:
        """Bin the unblanked samples; returns how many were binned."""
        now = self.clock() if now is None else now
        self._expire(now)
        on = ~np.asarray(blank, dtype=bool)
        if not on.any():
            return 0
        idx = self.bin_index(np.asarray(x)[on], np.asarray(y)[on])
        hist = self._current(now)
        hist += np.bincount(idx, minlength=hist.size).astype(np.float32)
        n = int(idx.size)
        self.total += n
        return n

    def image(self, now: float | None = None) -> np.ndarray:
        """Retained intensity, shape (resolution, resolution), float32."""
        now = self.clock() if now is None else now
        self._expire(now)
        r = self.resolution
        out = np.zeros(r * r, dtype=np.float32)
        for t0, h in self._buckets:
            if self.fade and not self.infinite:
                age = now - min(now, t0 + 0.5 * self.bucket_s)
                w = 1.0 - age / self.retention_s
                if w <= 0:
                    continue
                out += np.float32(w) * h
            else:
                out += h
        return out.reshape(r, r)

    def render(self, now: float | None = None) -> np.ndarray:
        """8-bit display image (log intensity scaling, brightest pixel = 255; 0 = nothing)."""
        img = self.image(now)
        m = float(img.max()) if img.size else 0.0
        if m <= 0:
            return np.zeros(img.shape, dtype=np.uint8)
        v = np.log1p(img) * np.float32(254.0 / math.log1p(m))
        out = np.zeros(img.shape, dtype=np.uint8)
        hit = img > 0
        out[hit] = 1 + v[hit].astype(np.uint8)  # any hit is visible, however faint
        return out


def phosphor_lut() -> list[int]:
    """256 ARGB colours: black → green phosphor → near white."""
    lut = []
    for i in range(256):
        t = i / 255.0
        g = int(round(255 * min(1.0, 0.15 + 1.1 * t))) if i else 0
        r = b = int(round(255 * max(0.0, (t - 0.7) / 0.3) * 0.85)) if i else 0
        lut.append(0xFF000000 | (r << 16) | (g << 8) | b)
    return lut


# ==================================================================== worker thread
@dataclass
class MonitorStats:
    rate: float = 0.0  # samples / s arriving through the tap (all, blanked included)
    unblanked: float = 0.0  # fraction of those that were plotted
    dropped: int = 0  # samples not handed off (tap full) since start
    pushed: int = 0
    total: int = 0  # samples binned since the last clear
    #: the beam now, in field volts (image coordinates): (x, y, blanked); None = unknown
    spot: tuple[float, float, bool] | None = None


class ScanMonitorWorker:
    """Drains a :class:`ScanTap` into a :class:`PersistenceAccumulator` and renders frames.

    Runs in its own thread; ``on_frame(image_uint8, stats)`` is called from
    that thread every ``interval_s``.  Settings changes and :meth:`clear` are
    applied by the worker thread itself.
    """

    def __init__(self, tap: ScanTap, on_frame: Callable[[np.ndarray, MonitorStats], None],
                 resolution: int = 256, retention_s: float = 2.0, fade: bool = True, interval_s: float = 0.1,
                 orientation: tuple[bool, bool, bool] = (False, False, False)):
        self.tap = tap
        self.on_frame = on_frame
        self.interval_s = float(interval_s)
        ix, iy, sw = orientation
        self.acc = PersistenceAccumulator(resolution, retention_s, fade, invert_x=ix, invert_y=iy, swap_xy=sw)
        self._pending: dict = {}
        self._clear = False
        self._stop = threading.Event()
        self._thread: threading.Thread | None = None
        self.skip_frame: Callable[[], bool] = lambda: False  # the display is still busy with the last one

    @property
    def running(self) -> bool:
        return self._thread is not None and self._thread.is_alive()

    def configure(self, resolution: int | None = None, retention_s: float | None = None,
                  fade: bool | None = None, orientation: tuple[bool, bool, bool] | None = None) -> None:
        """Change settings (applied by the worker thread).  *orientation* = (invert_x, invert_y, swap_xy)
        of the scan outputs; changing it clears the screen."""
        if resolution is not None:
            self._pending["resolution"] = int(resolution)
        if retention_s is not None:
            self._pending["retention_s"] = float(retention_s)
        if fade is not None:
            self._pending["fade"] = bool(fade)
        if orientation is not None:
            self._pending["orientation"] = tuple(bool(v) for v in orientation)

    def clear(self) -> None:
        self._clear = True

    def start(self) -> "ScanMonitorWorker":
        if self.running:
            return self
        self._stop.clear()
        self.tap.clear()
        self.tap.enabled = True
        self._thread = threading.Thread(target=self._run, name="easyebl-scan-monitor", daemon=True)
        self._thread.start()
        return self

    def stop(self, timeout: float = 2.0) -> None:
        self.tap.enabled = False
        self._stop.set()
        t = self._thread
        if t is not None and t is not threading.current_thread():
            t.join(timeout)
        self._thread = None

    def _apply(self) -> None:
        p, self._pending = self._pending, {}
        a = self.acc
        orient = p.get("orientation", a.orientation)
        if p.get("resolution", a.resolution) != a.resolution or orient != a.orientation:
            ix, iy, sw = orient
            self.acc = a = PersistenceAccumulator(p.get("resolution", a.resolution), a.retention_s, a.fade,
                                                  a.full_scale_v, a.n_buckets, a.clock, ix, iy, sw)
        if "retention_s" in p:
            a.retention_s = p["retention_s"]  # the existing buckets expire by the new time
        if "fade" in p:
            a.fade = p["fade"]
        if self._clear:
            self._clear = False
            a.clear()

    def step(self, now: float | None = None) -> tuple[np.ndarray, MonitorStats, int]:
        """One iteration (also usable without the thread): drain, bin, render."""
        self._apply()
        x, y, b = self.tap.pop()
        n_on = self.acc.add(x, y, b, now)
        frame = self.acc.render(now)
        spot = self.tap.position()
        if spot is not None:
            fx, fy = self.acc.to_field(spot[0], spot[1])
            spot = (float(fx), float(fy), spot[2])
        st = MonitorStats(dropped=self.tap.dropped, pushed=self.tap.pushed, total=self.acc.total,
                          unblanked=(n_on / len(x)) if len(x) else 0.0, spot=spot)
        return frame, st, len(x)

    def _run(self) -> None:
        t_last = time.monotonic()
        while not self._stop.is_set():
            t0 = time.monotonic()
            try:
                frame, st, n = self.step()
                dt = max(1e-6, t0 - t_last)
                st.rate = n / dt
                t_last = t0
                if not self.skip_frame():
                    self.on_frame(frame, st)
            except Exception:  # noqa: BLE001 - a display problem must never end the monitor
                pass
            self._stop.wait(max(0.0, self.interval_s - (time.monotonic() - t0)))
