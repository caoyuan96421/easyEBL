"""Abstract DAQ backend interface.

A backend knows how to talk to one piece of hardware (or a simulator).  It is
*not* thread-safe and is never used directly by application modules; they go
through :class:`easyebl.hal.manager.DAQManager` / :class:`DAQHandle`, which
serialise access and enforce the safe state.
"""
from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
import threading
from typing import Callable, Iterable, Sequence

import numpy as np

from ..core.waveform import OutputChunk
from .config import AUX_OUTPUTS, DAQConfig

__all__ = [
    "DAQBackend",
    "BackendCapabilities",
    "StreamResult",
    "HALError",
    "DeviceBusyError",
    "ResourceConflictError",
    "VoltageRangeError",
    "StreamAborted",
    "StreamUnderflowError",
    "StreamOverflowError",
    "DeviceLostError",
    "StreamMonitor",
    "AIConsumer",
]

#: Called with each block of acquired AI samples, shape (n_channels, n_samples),
#: in acquisition order.  Sample ``k`` of the stream was taken on the same
#: clock edge as output sample ``k``.
AIConsumer = Callable[[np.ndarray], None]


class HALError(RuntimeError):
    """Base class for HAL errors."""


class DeviceBusyError(HALError):
    """The device is executing another hardware-timed operation."""


class ResourceConflictError(HALError):
    """A resource (line/channel) is claimed by another handle."""


class VoltageRangeError(HALError):
    """An output sample exceeds the configured AO limit."""


class StreamAborted(HALError):
    """Raised (internally) when a stream is aborted by request."""


class DeviceLostError(HALError):
    """Communication with the device was lost (unplugged, powered off, USB error).

    The manager marks the device as disconnected, refuses further operations
    immediately (no hangs) and – unless disabled – reconnects by itself when
    the device answers again.
    """


class StreamUnderflowError(HALError):
    """The host did not supply output samples fast enough (output buffer ran empty).

    The hardware stopped generating; the HAL has already returned the beam to
    the safe state.  Retrying with a larger ``latency_s`` usually helps.
    """


class StreamOverflowError(HALError):
    """Acquired samples were overwritten before the host read them (AI buffer full)."""


@dataclass
class StreamMonitor:
    """Live counters of a running stream, updated by the backend.

    Plain attribute writes (atomic in CPython), so any thread may read them
    for status displays and health checks while the stream runs.
    """

    rate: float = 0.0
    buffer_samples: int = 0  # output buffer depth = output latency budget
    piece_samples: int = 0  # write granularity
    ai_buffer_samples: int = 0
    written: int = 0  # samples handed to the driver
    generated: int = 0  # samples generated by the device (last poll)
    ai_read: int = 0
    out_fill_min: int | None = None  # lowest observed output backlog after start (samples)
    ai_backlog_max: int = 0  # largest AI backlog observed (samples per channel)
    writes: int = 0
    running: bool = False
    t_start: float = 0.0
    t_update: float = 0.0  # perf_counter of the last update (stall detection)

    @property
    def latency_s(self) -> float:
        return self.buffer_samples / self.rate if self.rate else 0.0

    @property
    def margin_s(self) -> float | None:
        """Smallest output backlog seen, in seconds (≈ how close we came to an underflow)."""
        if self.out_fill_min is None or not self.rate:
            return None
        return self.out_fill_min / self.rate


@dataclass
class BackendCapabilities:
    name: str
    max_ao_rate: float
    max_ai_aggregate_rate: float
    ai_channels: tuple
    timed_lines: tuple
    static_lines: tuple
    simulated: bool = False
    external_control: bool = False  # SEM internal/external scan switch available


@dataclass
class StreamResult:
    """Outcome of :meth:`DAQBackend.run_stream`."""

    samples_written: int
    rate: float
    aborted: bool = False
    ai: np.ndarray | None = None  # (n_ch, n) when no consumer was given
    ai_channels: tuple = ()
    elapsed_s: float = 0.0
    info: dict = field(default_factory=dict)


class DAQBackend(ABC):
    """Hardware (or simulator) implementation."""

    def __init__(self, config: DAQConfig):
        config.validate()
        self.config = config
        self._open = False
        self.phantom = None  # PhantomSpecimen / EDSPhantomSpecimen driving the phantom outputs
        self._phantom_key = None
        # photon listeners of the EDS phantom live here, so they survive a phantom rebuild
        self._photon_listeners: list = []
        self._photon_lock = threading.Lock()
        self.aux_values: dict = {k: 0.0 for k in AUX_OUTPUTS}  # last value set per aux output

    # ---------------------------------------------------------------- lifecycle
    @property
    def is_open(self) -> bool:
        return self._open

    @abstractmethod
    def open(self) -> None: ...

    @abstractmethod
    def close(self) -> None: ...

    @abstractmethod
    def capabilities(self) -> BackendCapabilities: ...

    # ------------------------------------------------------------------- static
    @abstractmethod
    def write_static(self, x_v: float, y_v: float, blank: bool) -> None:
        """Immediately set deflection voltages and the blanker (software timed)."""

    @abstractmethod
    def set_static_line(self, name: str, value: bool) -> None:
        """Set a software-timed auxiliary line (logical value, polarity applied)."""

    @abstractmethod
    def set_external_control(self, on: bool) -> None:
        """Switch the SEM to external (DAQ) scan (*on*) or back to its internal scan.

        Drives every wire of ``config.external_control_lines`` with its own
        polarity (see :meth:`external_levels`).  Called by the manager only
        (never during a stream).
        """

    # ------------------------------------------------------------------ streams
    @abstractmethod
    def run_stream(
        self,
        rate: float,
        chunks: Iterable[OutputChunk],
        ai_channels: Sequence[str] = (),
        on_ai: AIConsumer | None = None,
        abort: threading.Event | None = None,
        progress: Callable[[int], None] | None = None,
        latency_s: float | None = None,
        monitor: StreamMonitor | None = None,
        ai_range_v: float | None = None,
    ) -> StreamResult:
        """Play a sample-clocked output stream, acquiring AI on the same clock.

        ``latency_s`` bounds how far (in time) the host may run ahead of the
        beam – the output buffer depth.  Small values make parameter changes
        take effect sooner; large values tolerate longer host stalls.  None =
        the configured default.  ``monitor`` receives live counters;
        ``ai_range_v`` overrides the configured AI input range for this stream.

        Implementations must:
        * generate X, Y, blank and marker lines from one sample clock;
        * acquire the requested AI channels on that same clock, one AI sample
          per output sample;
        * check *abort* between chunks and stop promptly when set;
        * leave the hardware in the safe state (blanked, parked) on exit, even
          on error.
        """

    # ------------------------------------------------------------ aux outputs
    def set_aux_output(self, name: str, volts: float) -> None:
        """Set aux analog output *name* (``aux0``/``aux1``).  A dummy output only records the value."""
        phys = self.config.aux_physical(name)
        if phys:
            self._write_aux(phys, float(volts))
        self.aux_values[name] = float(volts)

    def _write_aux(self, physical: str, volts: float) -> None:
        """Write one physical AO channel statically (backends with real aux outputs)."""

    def _phantom_obj(self):
        cfg = self.config
        key = (cfg.phantom_kind, cfg.ao_limit_v,
               tuple(sorted((k, v) for k, v in cfg.eds_phantom.items() if k != "cps")))
        if self.phantom is None or self._phantom_key != key:
            old = self.phantom
            if cfg.phantom_kind == "eds":
                from .eds_phantom import EDSPhantomSpecimen

                ph = EDSPhantomSpecimen(extent_v=cfg.ao_limit_v, noise_v=cfg.phantom_noise_v, **cfg.eds_phantom)
                ph._listeners = self._photon_listeners  # shared registry
                ph._llock = self._photon_lock
                if old is not None and hasattr(old, "clock_s"):
                    ph.clock_s = old.clock_s  # the detector clock never runs backwards
            else:
                from .phantom import PhantomSpecimen

                ph = PhantomSpecimen(extent_v=cfg.ao_limit_v, noise_v=cfg.phantom_noise_v)
            self.phantom, self._phantom_key = ph, key
        self.phantom.noise_v = float(cfg.phantom_noise_v)  # may change between/while streams
        if cfg.phantom_kind == "eds" and "cps" in cfg.eds_phantom:
            self.phantom.set_cps(float(cfg.eds_phantom["cps"]))
        return self.phantom

    def phantom_source(self):
        """The phantom image source for streams, or None (no phantom / routed to a dummy output)."""
        if not self.config.phantom_physical:
            return None
        return self._phantom_obj()

    def eds_phantom(self):
        """The EDS phantom specimen (photons + SDD signal) when ``phantom_kind == "eds"``, else None.

        Streams generate its photons whether or not the SDD output is physical, so a
        simulated pulse processor works with any backend.
        """
        if self.config.phantom_kind != "eds":
            return None
        return self._phantom_obj()

    def prepare_phantom(self) -> None:
        """Build the phantom now (≈0.5–2 s once) rather than inside a stream start."""
        if self.config.phantom_physical or self.config.phantom_kind == "eds":
            self._phantom_obj()

    # photon listeners: fn(t0_s, dt_s, sample_idx, energies_kev, n_samples) per stream chunk
    def add_photon_listener(self, fn) -> None:
        with self._photon_lock:
            if fn not in self._photon_listeners:
                self._photon_listeners.append(fn)

    def remove_photon_listener(self, fn) -> None:
        with self._photon_lock:
            if fn in self._photon_listeners:
                self._photon_listeners.remove(fn)

    # ------------------------------------------------------- connection health
    def probe(self) -> bool:
        """Is the device reachable right now?  Must not disturb any output.

        Called by the manager only while no stream runs (e.g. by the reconnect
        watchdog after a :class:`DeviceLostError`).
        """
        return True

    def is_device_lost(self, exc: BaseException) -> bool:
        """Does *exc* (raised by this backend) mean the device has gone away?"""
        return isinstance(exc, DeviceLostError)

    def recover(self) -> None:
        """Re-establish communication after the device came back (close + open)."""
        try:
            self.close()
        except Exception:  # noqa: BLE001 - the old session may be dead
            self._open = False
        self.open()

    # ------------------------------------------------------------------ helpers
    def blank_level(self, blank: bool) -> bool:
        """Electrical level for a logical blank state."""
        return bool(blank) if self.config.blank_active_high else not bool(blank)

    def external_levels(self, on: bool) -> dict:
        """Electrical level of each external-control wire for logical state *on*."""
        return {w: (bool(on) if hi else not bool(on)) for w, hi in self.config.external_control_map().items()}

    def static_level(self, name: str, value: bool) -> bool:
        active_high = self.config.static_lines_active_high.get(name, True)
        return bool(value) if active_high else not bool(value)

    def safe_state(self) -> None:
        self.write_static(self.config.park_x_v, self.config.park_y_v, True)
